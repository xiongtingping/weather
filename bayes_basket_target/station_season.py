_QUARTER_LABELS = (
    SEASON_PEAK,
    SEASON_DESCENT,
    SEASON_TROUGH,
    SEASON_ASCENT,
)


def station_season_bin(station_id: str, day: str) -> str:
    """The station-local season label for one event date.

    ``day`` is an ISO ``YYYY-MM-DD`` local date.  Unknown stations fail
    closed: a label invented for an unmapped station would silently key
    artifacts nothing can ever look up again.
    """

    station = str(station_id or "").strip().upper()
    if station not in _SEASON_ANCHOR_MONTH:
        raise ContractError("station_season_station_unmapped")
    try:
        month = int(str(day)[5:7])
    except (ValueError, IndexError) as exc:
        raise ContractError("station_season_event_date_invalid") from exc
    if not 1 <= month <= 12:
        raise ContractError("station_season_event_date_invalid")
    anchor = _SEASON_ANCHOR_MONTH[station]
    if anchor is None:
        return SEASON_ALLYEAR
    # Quarters of the station's own cycle: PEAK is centred on the anchor
    # month, so it spans anchor-1 .. anchor+1, and the other three follow.
    offset = (month - anchor + 1) % 12
    return _QUARTER_LABELS[offset // 3]


def season_bins_for_window(
    station_id: str,
    start_day: str,
    end_day: str,
) -> tuple[str, ...]:
    """Every label an artifact must carry to serve [start_day, end_day].

    This is the boundary-continuity half of charter 62: an artifact fitted
    days before a station's season boundary is emitted under every label its
    validity window will be asked for, so the boundary date never finds an
    empty scope.  Ordered first-served-first, deduplicated.
    """

    try:
        start = date.fromisoformat(str(start_day)[:10])
        end = date.fromisoformat(str(end_day)[:10])
    except ValueError as exc:
        raise ContractError("station_season_window_invalid") from exc
    if end < start:
        raise ContractError("station_season_window_invalid")
    labels: list[str] = []
    cursor = start.replace(day=1)
    while cursor <= end:
        label = station_season_bin(station_id, cursor.isoformat())
        if label not in labels:
            labels.append(label)
        cursor = (cursor + timedelta(days=32)).replace(day=1)
    first_label = station_season_bin(station_id, start.isoformat())
    if labels[0] != first_label:
        labels.remove(first_label)
        labels.insert(0, first_label)
    return tuple(labels)
