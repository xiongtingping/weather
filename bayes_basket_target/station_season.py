"""Station-local seasons anchored on each station's own hottest months.

Charter 62 (2026-08-25): the season vocabulary is not the calendar.  Ten of
the forty-five stations peak outside June-August -- the southern quartet
(SAEZ, FACT, NZWN, SBGR) in January-February, the pre-monsoon group (VILK,
OPKC, RPLL, MMMX) in April-May, the marine-lagged Californians (KSFO, KLAX)
in September -- so a DJF/MAM/JJA/SON partition assigns most of the fleet a
season that is not theirs.  Seasons here are quarters of each station's own
annual temperature cycle, rotated so the hottest month sits at the centre
of PEAK.

The anchor table below is derived from the frozen ERA5 same-day climatology
capture (9 balanced years, 2016-08-14 to 2025-08-14) by
``scripts/build_station_season_map.py``: anchor month = argmax of the
3-month centered running mean of the monthly means (the raw argmax splits
July/August inside year-to-year noise at 16 stations), and a station whose
annual amplitude is under 2.0C has no usable phase at all -- WMKK and WSSS
sit essentially on the equator -- so it carries anchor ``None`` and lives
in the single ALLYEAR bin.

The vocabulary is deliberately disjoint from both legacy vocabularies (the
DJF trigrams and the hemisphere-flipped English names): a label can never
be mistaken for a calendar claim, and an exact join between the two
vocabularies fails loudly instead of matching the wrong rows -- the
2026-07-31 summer/JJA silent-join break is the specimen this guards
against.

These labels are lineage identity.  Training does not partition by them
(charter 62 makes the fit window a rolling tail window, cross-season by
construction); they say which serving dates an artifact was emitted for.
"""

